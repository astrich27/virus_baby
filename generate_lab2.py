def rpr(bold=False, italic=False, size=None):
    bits = []
    if bold: bits.append('<w:b/>')
    if italic: bits.append('<w:i/>')
    if size: bits.append(f'<w:sz w:val="{size}"/><w:szCs w:val="{size}"/>')
    return '<w:rPr>' + ''.join(bits) + '</w:rPr>' if bits else ''

def p(text='', style='Normal', bold=False, italic=False, size=None, align=None, page_break=False):
    props = f'<w:pPr><w:pStyle w:val="{style}"/>'
    if align: props += f'<w:jc w:val="{align}"/>'
    props += '</w:pPr>'
    run = f'<w:r>{rpr(bold, italic, size)}<w:t xml:space="preserve">{escape(text)}</w:t></w:r>'
    br = '<w:r><w:br w:type="page"/></w:r>' if page_break else ''
    return '<w:p>' + props + br + run + '</w:p>'

def heading(text, level=1):
    return p(text, f'Heading{level}')

def bullet(text):
    return p('• ' + text, 'Normal')

def table(rows, widths=None):
    cols = len(rows[0])
    grid = ''.join(f'<w:gridCol w:w="{(widths or [3000//cols]*cols)[i]}"/>' for i in range(cols))
    out = [f'<w:tbl><w:tblPr><w:tblStyle w:val="TableGrid"/><w:tblW w:w="0" w:type="auto"/></w:tblPr><w:tblGrid>{grid}</w:tblGrid>']
    for ri, row in enumerate(rows):
        out.append('<w:tr>')
        for cell in row:
            text = str(cell)
            out.append('<w:tc><w:tcPr><w:tcMar><w:top w:w="80" w:type="dxa"/><w:bottom w:w="80" w:type="dxa"/><w:start w:w="100" w:type="dxa"/><w:end w:w="100" w:type="dxa"/></w:tcMar></w:tcPr>')
            out.append(p(text, 'Normal', bold=(ri == 0)))
            out.append('</w:tc>')
        out.append('</w:tr>')
    out.append('</w:tbl>')
    return ''.join(out)

def codeblock(text):
    result = []
    for line in text.strip('\n').splitlines():
        result.append(p(line, 'Normal', size=18))
    return ''.join(result)

